"use strict";
const { contextBridge, ipcRenderer, webUtils } = require("electron");
const call = async (n, ...a) => { const r = await ipcRenderer.invoke(n, ...a); if (!r.ok) throw new Error(r.error); return r.data; };
contextBridge.exposeInMainWorld("api", {
  load: () => call("load"),
  save: text => call("save", text),
  setup: o => call("setup", o),
  pickFolder: (t, d) => call("pickFolder", t, d),
  checkFolder: d => call("checkFolder", d),
  moveData: o => call("moveData", o),
  setCfg: p => call("setCfg", p),
  backup: () => call("backup"),
  listBackups: () => call("listBackups"),
  restore: f => call("restore", f),
  openPath: r => call("openPath", r),
  showItem: r => call("showItem", r),
  importFiles: o => call("importFiles", o),
  writeImage: o => call("writeImage", o),
  deleteFile: r => call("deleteFile", r),
  pdf: o => call("pdf", o),
  print: () => call("print"),
  saveText: o => call("saveText", o),
  mail: o => call("mail", o),
  hash: t => call("hash", t),
  openManual: () => call("openManual"),
  openDoc: n => call("openDoc", n),
  pathOf: file => webUtils.getPathForFile(file),
  http: o => call("http", o),
  secretSet: (name, value) => call("secretSet", { name, value }),
  secretGet: name => call("secretGet", name),
  secretClear: () => call("secretClear"),
  fileStat: r => call("fileStat", r),
  readB64: r => call("readB64", r),
  writeB64: (rel, b64) => call("writeB64", { rel, b64 }),
  loadSync: () => call("loadSync"),
  saveSync: t => call("saveSync", t),
  dropSync: () => call("dropSync"),
  openExternal: u => call("openExternal", u),
  deviceInfo: () => call("deviceInfo"),
  onBeforeClose: fn => ipcRenderer.on("before-close", fn)
});
